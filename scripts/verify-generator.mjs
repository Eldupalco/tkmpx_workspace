function run(dir, label, command) {
  console.log(`\n▶ ${label}`);
  execSync(command, { cwd: dir, stdio: 'inherit', env: { ...process.env, CI: 'true' } });
}

function checkUnits() {
  const source = `import { Module } from '@nestjs/common';
import { ConfigModule } from '@nestjs/config';

@Module({
  imports: [ConfigModule.forRoot({ isGlobal: true, load: [a, b] }), UsersModule,],
})
export class AppModule {}
`;
  const once = registerModule(source, { className: 'TicketModule', importPath: './ticket/ticket.module.js' });
  assert.equal(once.status, 'registered');
  assert.match(once.source, /load: \[a, b\] \}\), UsersModule, TicketModule,\]/);
  assert.match(once.source, /import \{ TicketModule \} from '\.\/ticket\/ticket\.module\.js';/);
  const twice = registerModule(once.source, { className: 'TicketModule', importPath: './ticket/ticket.module.js' });
  assert.equal(twice.status, 'already-registered');

  const schemaFile = path.join(root, 'prisma', 'schema.prisma');
  const legacy = parseGenerator([[schemaFile, 'generator client {\n  provider = "prisma-client-js"\n}']], root);
  assert.deepEqual(legacy, { client: '@prisma/client', enums: '@prisma/client' });
  const custom = parseGenerator([[schemaFile, 'generator client {\n  provider = "prisma-client"\n  output = "../lib/db"\n}']], root);
  assert.deepEqual(custom, { client: 'lib/db/client', enums: 'lib/db/enums' });
  const plurals = { statuses: 'status', analysis: 'analysis', news: 'news', categories: 'category', addresses: 'address', people: 'person', houses: 'house', ProductCategories: 'ProductCategory' };
  for (const [plural, singular] of Object.entries(plurals)) assert.equal(toSingular(plural), singular, `singular of ${plural}`);
  console.log('✔ app.module registration, generator detection and naming');
}

async function checkMultiFileSchema() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gen-schema-'));
  try {
    fs.writeFileSync(path.join(dir, 'main.prisma'), 'datasource db {\n  provider = "postgresql"\n}\n');
    fs.writeFileSync(
      path.join(dir, 'post.prisma'),
      'model Post {\n  id Int @id\n  title String\n  hashtags String[]\n  tokenCount Int\n  refreshToken String\n  apiKey String\n}\n',
    );
    const schema = await loadSchema(dir, '.');
    assert.equal(schema.models[0].name, 'Post');
    assert.equal(schema.provider, 'postgresql');
    const hidden = describeModel(schema, schema.models[0]).fields.filter((f) => f.isSensitive).map((f) => f.name);
    assert.deepEqual(hidden, ['refreshToken', 'apiKey']);
    console.log('✔ multi-file schema folder and sensitive-field detection');
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

// oxlint always skips .gitignore'd paths, so lint a copy outside the project
function lintGeneratedModules(dir) {
  const lintDir = fs.mkdtempSync(path.join(os.tmpdir(), 'gen-lint-'));
  try {
    for (const m of generatedModules) fs.cpSync(path.join(dir, 'src', m), path.join(lintDir, m), { recursive: true });
    console.log('\n▶ lint generated modules');
    execSync(`"${path.join(root, 'node_modules', '.bin', 'oxlint')}" -c "${path.join(root, 'oxlint.json')}" --deny-warnings .`, {
      cwd: lintDir,
      stdio: 'inherit',
    });
  } finally {
    fs.rmSync(lintDir, { recursive: true, force: true });
  }
}

function runScenario(scenario) {
  const dir = path.resolve('.gen-verify', scenario.name);
  console.log(`\n━━ Scenario: ${scenario.name} ━━`);
  fs.rmSync(dir, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 });
  fs.mkdirSync(dir, { recursive: true });
  for (const item of copyItems) {
    if (fs.existsSync(item)) fs.cpSync(item, path.join(dir, item), { recursive: true });
  }
  fs.appendFileSync(
    path.join(dir, 'prisma', 'schema.prisma'),
    '\n' + fs.readFileSync(path.join(root, 'scripts', 'generate-module', 'fixtures', 'edge-cases.prisma'), 'utf8'),
  );
  if (scenario.config) fs.writeFileSync(path.join(dir, 'gen-module.config.json'), JSON.stringify(scenario.config, null, 2));
  scenario.prepare?.(dir);

  run(dir, 'prisma generate', 'npx --no-install prisma generate --schema prisma/schema.prisma');
  run(dir, 'generate all modules', 'node scripts/generate-module.mjs --all --force --spec');
  scenario.check((p) => fs.readFileSync(path.join(dir, p), 'utf8'), dir);
  console.log('✔ generated output matches expectations');
  run(dir, 'type-check', 'npx --no-install tsc --noEmit -p tsconfig.json');
  lintGeneratedModules(dir);
  run(dir, 'generated specs', `npx --no-install vitest run ${generatedModules.map((m) => `src/${m}`).join(' ')}`);
  if (scenario.probe) runHttpProbe(dir);
  if (scenario.collisions) checkCollisions(dir);
  if (scenario.undo) checkUndo(dir);
}

// Full text of a file or folder tree, for before/after comparisons
function treeText(target) {
  if (!fs.existsSync(target)) return null;
  if (fs.statSync(target).isFile()) return fs.readFileSync(target, 'utf8');
  return fs
    .readdirSync(target, { recursive: true })
    .map(String)
    .sort()
    .filter((f) => fs.statSync(path.join(target, f)).isFile())
    .map((f) => `${f}\n${fs.readFileSync(path.join(target, f), 'utf8')}`)
    .join('\n');
}

// --undo must restore overwritten modules, remove new ones, and refuse to discard later edits
function checkUndo(dir) {
  console.log('\n▶ undo');
  const gen = (cmd) => execSync(`node scripts/generate-module.mjs ${cmd}`, { cwd: dir, stdio: 'pipe' }).toString();
  const ticketDir = path.join(dir, 'src', 'ticket');
  const ticketService = path.join(ticketDir, 'services', 'ticket.service.ts');
  const appModule = path.join(dir, 'src', 'app.module.ts');

  // 1. An accidental --force wipes a hand edit; --undo brings it back
  fs.appendFileSync(ticketService, '\n// hand edit\n');
  const editedTicket = treeText(ticketDir);
  gen('Ticket --force');
  assert.doesNotMatch(fs.readFileSync(ticketService, 'utf8'), /hand edit/);
  gen('--undo');
  assert.equal(treeText(ticketDir), editedTicket, 'overwritten module restored with the hand edit');

  // 2. Undoing a new module deletes it and unregisters it from app.module.ts
  fs.appendFileSync(path.join(dir, 'prisma', 'schema.prisma'), '\nmodel Note {\n  id String @id\n  body String\n}\n');
  const appBefore = treeText(appModule);
  gen('Note');
  assert.ok(fs.existsSync(path.join(dir, 'src', 'note')));
  gen('--undo');
  assert.ok(!fs.existsSync(path.join(dir, 'src', 'note')), 'new module removed');
  assert.equal(treeText(appModule), appBefore, 'app.module.ts restored');

  // 3. Edits made after a run block the undo unless --force is given
  gen('Ticket --force');
  fs.appendFileSync(ticketService, '\n// later edit\n');
  assert.throws(() => gen('--undo'), 'undo refused after later edits');
  gen('--undo --force');
  assert.equal(treeText(ticketDir), editedTicket, 'forced undo restores the pre-run state');

  assert.match(gen('--list-backups'), /undone/);
  console.log('✔ undo restores overwritten modules, removes new ones, and protects later edits');
}

function runHttpProbe(dir) {
  run(dir, 'compile for HTTP probe', 'npx --no-install tsc -p tsconfig.json --outDir dist-check --incremental false');
  fs.copyFileSync(path.join(root, 'scripts', 'generate-module', 'fixtures', 'http-probe.mjs'), path.join(dir, 'http-probe.mjs'));
  run(dir, 'HTTP probe', 'node http-probe.mjs');
}

// Names that would clash with hand-written code must be refused, even with --force
function checkCollisions(dir) {
  console.log('\n▶ name collisions');
  fs.appendFileSync(path.join(dir, 'prisma', 'schema.prisma'), '\nmodel App {\n  id String @id\n}\n\nmodel Auth {\n  id String @id\n}\n');
  const appModule = fs.readFileSync(path.join(dir, 'src', 'app.module.ts'), 'utf8');
  const authFiles = fs.readdirSync(path.join(dir, 'src', 'auth'), { recursive: true }).length;
  for (const model of ['App', 'Auth']) {
    let failed = false;
    try {
      execSync(`node scripts/generate-module.mjs ${model} --force`, { cwd: dir, stdio: 'pipe' });
    } catch {
      failed = true;
    }
    assert.ok(failed, `${model} must be refused`);
  }
  assert.equal(fs.readFileSync(path.join(dir, 'src', 'app.module.ts'), 'utf8'), appModule, 'app.module.ts unchanged');
  assert.equal(fs.readdirSync(path.join(dir, 'src', 'auth'), { recursive: true }).length, authFiles, 'src/auth untouched');

  execSync('node scripts/generate-module.mjs tickets --only=dto', { cwd: dir, stdio: 'pipe' });
  assert.ok(!fs.existsSync(path.join(dir, 'src', 'tickets')), '"tickets" maps to the existing src/ticket module');
  console.log('✔ App/Auth refused, src/auth untouched, "tickets" reuses src/ticket');
}

try {
  checkUnits();
  await checkMultiFileSchema();
  for (const scenario of scenarios) runScenario(scenario);
  console.log('\n✨ Generator verification passed.');
} catch (error) {
  console.error(`\n❌ Generator verification failed: ${error.message}`);
  process.exitCode = 1;
} finally {
  const scratch = path.resolve('.gen-verify');
  if (keep) console.log(`📁 Scratch copies kept at ${path.relative(root, scratch)}`);
  else fs.rmSync(scratch, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
}
