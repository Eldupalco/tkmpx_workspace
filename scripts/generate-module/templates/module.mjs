// The first line marks the folder as generator-owned, so --force may overwrite it
export const GENERATED_MARKER = 'Generated by gen:module';

export function moduleTemplate({ names, model, options, imp }) {
  const { pascalName } = names;
  // A non-global module that exports the auth guard must be imported for the guard's dependencies
  const authModule = typeof options.guard === 'object' && options.guard ? options.guard.module : null;
  const authImport = authModule ? `import { ${authModule.className} } from '${imp('module', 'authModule')}';\n` : '';
  const imports = authModule ? `\n  imports: [${authModule.className}],` : '';

  return `// ${GENERATED_MARKER} from Prisma model "${model.modelName}"
import { Module } from '@nestjs/common';
${authImport}import { ${pascalName}Controller } from '${imp('module', 'controller')}';
import { ${pascalName}Service } from '${imp('module', 'service')}';

@Module({${imports}
  controllers: [${pascalName}Controller],
  providers: [${pascalName}Service],
  exports: [${pascalName}Service],
})
export class ${pascalName}Module {}
`;
}

// Smoke specs (--spec) for Vitest or Jest
function specHeader(framework) {
  return framework === 'vitest' ? `import { describe, it, expect, beforeEach, vi } from 'vitest';\n` : '';
}

const mockFn = (framework) => (framework === 'vitest' ? 'vi.fn' : 'jest.fn');

export function controllerSpecTemplate({ names, options, imp }) {
  const { pascalName } = names;
  const fn = mockFn(options.testFramework);
  // JwtAuthGuard-style guards resolve JwtService when the controller is compiled
  const jwtImport = options.jwtMock ? `import { JwtService } from '@nestjs/jwt';\n` : '';
  const jwtProvider = options.jwtMock ? `\n        { provide: JwtService, useValue: { verifyAsync: ${fn}() } },` : '';

  return `import { Test, TestingModule } from '@nestjs/testing';
${specHeader(options.testFramework)}${jwtImport}import { ${pascalName}Controller } from '${imp('controllerSpec', 'controller')}';
import { ${pascalName}Service } from '${imp('controllerSpec', 'service')}';

describe('${pascalName}Controller', () => {
  let controller: ${pascalName}Controller;

  const mockService = {
    create: ${fn}(),
    findAll: ${fn}(),
    findOne: ${fn}(),
    update: ${fn}(),
    remove: ${fn}(),
  };

  beforeEach(async () => {
    const module: TestingModule = await Test.createTestingModule({
      controllers: [${pascalName}Controller],
      providers: [
        { provide: ${pascalName}Service, useValue: mockService },${jwtProvider}
      ],
    }).compile();

    controller = module.get<${pascalName}Controller>(${pascalName}Controller);
  });

  it('should be defined', () => {
    expect(controller).toBeDefined();
  });
});
`;
}

export function serviceSpecTemplate({ names, model, options, config, imp }) {
  const { pascalName } = names;
  const fn = mockFn(options.testFramework);
  const prismaService = config.prismaService.className;

  return `import { Test, TestingModule } from '@nestjs/testing';
${specHeader(options.testFramework)}import { ${pascalName}Service } from '${imp('serviceSpec', 'service')}';
import { ${prismaService} } from '${imp('serviceSpec', 'prismaService')}';

describe('${pascalName}Service', () => {
  let service: ${pascalName}Service;

  const mockPrismaService = {
    ${model.delegate}: {
      create: ${fn}(),
      findMany: ${fn}(),
      findUnique: ${fn}(),
      count: ${fn}().mockResolvedValue(0),
      update: ${fn}(),
      delete: ${fn}(),
    },
  };

  beforeEach(async () => {
    const module: TestingModule = await Test.createTestingModule({
      providers: [
        ${pascalName}Service,
        { provide: ${prismaService}, useValue: mockPrismaService },
      ],
    }).compile();

    service = module.get<${pascalName}Service>(${pascalName}Service);
  });

  it('should be defined', () => {
    expect(service).toBeDefined();
  });
});
`;
}
